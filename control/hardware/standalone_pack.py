"""Build an independent script with portable-bundle or plain-point JSON offline."""
import ast
import base64
import copy
import hashlib
import json
from pathlib import Path

from .trajectory_contract import load_bundle, read_json, sha256, write_json
from .standalone_runtime import (AUDIT_FILES, BASE_FILES, PORTABLE_SCHEMA, portable_filename,
                                 standalone_source_gate)
from .standalone_plain import PLAIN_CONTRACT, POINT_FIELDS, SOURCE_HASH_FIELDS, canonical_sha256


RUNTIME_MODULES = ('trajectory_contract.py', 'ros_runner.py', 'ros1_trajectory.py',
                   'standalone_keyboard.py', 'standalone_plain.py', 'standalone_runtime.py')


def build_standalone_script(config=None, reference=None, *, backend='protected',
                            expected_sha256=None, allow_retiming=False):
    """Static concatenation keeps generated code reviewable and authoritative."""
    directory = Path(__file__).parent
    if backend not in ('protected', 'moveit'):
        raise ValueError('Unsupported standalone backend')
    sections = ['#!/usr/bin/env python3\n'
                '# Generated by control.hardware standalone_pack.\n'
                '# Edit only SITE_DEPLOYMENT if present; rebuild runtime/reference data.\n'
                '# Requires Python 3, NumPy and ROS 1 UR message/communication packages.\n']
    modules, selected = RUNTIME_MODULES, {}
    if backend == 'moveit':
        if not isinstance(expected_sha256, str) or len(expected_sha256) != 64:
            raise ValueError('MoveIt script needs its paired trajectory SHA256')
        sections = ['#!/usr/bin/env python3\n'
            '# Generated from control.hardware; rebuild runtime changes in the project.\n'
            '# Requires Python 3, NumPy, ROS 1 and MoveIt. No trajectory data is embedded.\n'
            '# Defaults: manipulator / base_link / tool0; override through --help options.\n'
            'EXPECTED_TRAJECTORY_SHA256 = '+repr(expected_sha256)+'\n'
            'ALLOW_RETIMING = '+repr(bool(allow_retiming))+'\n'
            'MOVEIT_SCRIPT_PATH = __file__\n']
        modules = ('trajectory_contract.py', 'ros1_trajectory.py', 'standalone_keyboard.py', 'moveit_runtime.py')
        selected = {'trajectory_contract.py': {'sha256', 'write_json', 'unique_json_object',
                                               'quintic', 'bernstein_bounds'},
                    'ros1_trajectory.py': {'fill_joint_trajectory'}}
    elif reference is not None:
        sections.append('import json\n\n'
            '# EDITABLE SITE CONFIGURATION: fill verified workstation settings here.\n'
            '# Original three hashes describe the source bundle; plain bindings are separate.\n'
            'SITE_DEPLOYMENT = json.loads(r\'\'\'\n'+json.dumps(config, ensure_ascii=True, indent=2,
                allow_nan=False).replace("'", '\\u0027')+'\n\'\'\')\n\n'
            '# FIXED PAIRED REFERENCE: regenerate with standalone-pack when inputs change.\n'
            'PLAIN_SCRIPT_PATH = __file__\n'
            'PLAIN_REFERENCE_SHA256 = '+repr(canonical_sha256(reference))+'\n'
            'PLAIN_REFERENCE = json.loads(r\'\'\'\n'+json.dumps(reference, ensure_ascii=True, indent=2,
                allow_nan=False).replace("'", '\\u0027')+'\n\'\'\')\n')
    definitions = set()
    for name in modules:
        raw = (directory/name).read_bytes()
        source = raw.decode('utf-8')
        tree = ast.parse(source)
        omit = set()
        for node in tree.body:
            if name in selected and not isinstance(node, (ast.Import, ast.ImportFrom)) and (
                    not isinstance(node, (ast.FunctionDef, ast.ClassDef)) or node.name not in selected[name]):
                omit.update(range(node.lineno, node.end_lineno+1))
                continue
            if isinstance(node, (ast.FunctionDef, ast.ClassDef)):
                if node.name in definitions:
                    raise ValueError('Conflicting standalone definition: '+node.name)
                definitions.add(node.name)
            if isinstance(node, ast.ImportFrom) and node.level:
                omit.update(range(node.lineno, node.end_lineno+1))
            elif isinstance(node, ast.Expr) and isinstance(node.value, ast.Constant) and isinstance(node.value.value, str):
                omit.update(range(node.lineno, node.end_lineno+1))
        body = '\n'.join(line for i, line in enumerate(source.splitlines(), 1) if i not in omit)
        sections.append('\n# --- '+name+' sha256='+hashlib.sha256(raw).hexdigest()+' ---\n'+body+'\n')
    entry = 'moveit_main' if backend == 'moveit' else 'standalone_main'
    sections.append("\nif __name__ == '__main__':\n    raise SystemExit("+entry+"())\n")
    result = '\n'.join(sections)
    for node in ast.walk(ast.parse(result)):
        if isinstance(node, ast.Import):
            names = [alias.name for alias in node.names]
        elif isinstance(node, ast.ImportFrom):
            if node.level:
                raise ValueError('Relative import remains in standalone script')
            names = [node.module or '']
        else:
            continue
        forbidden = {'control', 'planning', 'perception', 'pipeline', 'mujoco', 'toppra', 'open3d', 'scipy'}
        if backend != 'moveit':
            forbidden.add('moveit_commander')
        if any(name.split('.')[0] in forbidden for name in names):
            raise ValueError('Nonportable import: '+str(names))
    compile(result, 'ur7e_saved_trajectory_executor.py', 'exec')
    return result


def pack_standalone(trajectory, deployment, output, *, allow_geometry_only=False, format='portable', backend='protected'):
    if format not in ('portable', 'plain'):
        raise ValueError('Standalone format must be portable or plain')
    if backend not in ('protected', 'moveit') or (backend == 'moveit' and format != 'plain'):
        raise ValueError('MoveIt backend requires --format plain')
    trajectory = Path(trajectory)
    if trajectory.name != 'trajectory.json':
        raise ValueError('Input must be the original exported trajectory.json')
    curve, report, manifest = load_bundle(trajectory)
    if backend == 'moveit':
        policy = ({'mode': 'geometry_only', 'acknowledge_unverified_motion': True}
                  if allow_geometry_only else {'mode': 'full'})
        blockers = standalone_source_gate(curve, report, {'execution_policy': policy})
        if blockers:
            raise ValueError('MoveIt build source gate: '+', '.join(blockers))
        payload = {'joint_names': curve.names,
                   'points': [{key: p[key] for key in POINT_FIELDS} for p in curve.record['points']]}
        output = Path(output)
        output.mkdir(parents=True, exist_ok=False)
        write_json(output/'trajectory.json', payload)
        digest = sha256(output/'trajectory.json')
        script = build_standalone_script(backend='moveit', expected_sha256=digest,
                                         allow_retiming=allow_geometry_only)
        (output/'ur7e_saved_trajectory_executor.py').write_text(script, encoding='utf-8', newline='\n')
        return dict(backend=backend, format=format, points=len(curve.times), duration_s=curve.duration,
            trajectory=str((output/'trajectory.json').resolve()),
            script=str((output/'ur7e_saved_trajectory_executor.py').resolve()),
            plain_trajectory_sha256=digest, script_sha256=sha256(output/'ur7e_saved_trajectory_executor.py'),
            source_check_mode=curve.record['source']['check_mode'], execution_policy=policy,
            hardware_validated=False)
    if deployment is None:
        raise ValueError('Protected backend requires --deployment')
    config = copy.deepcopy(read_json(deployment))
    if not isinstance(config, dict):
        raise ValueError('Deployment must be an object')
    names = BASE_FILES | set(manifest['snapshots'])
    names |= {name for name in AUDIT_FILES if (trajectory.parent/name).is_file()}
    if any(not portable_filename(name) for name in names):
        raise ValueError('Unsupported bundle filename')
    files = ({name: base64.b64encode((trajectory.parent/name).read_bytes()).decode('ascii')
              for name in sorted(names)} if format == 'portable' else {})
    # Fill only known facts; never invent site evidence or operator approval.
    for key, value in (('robot_model', 'ur7e'), ('joint_names', curve.names),
                       ('controller_interpolation', 'quintic'),
                       ('command_owner', 'exclusive_follow_joint_trajectory')):
        if config.get(key) is None:
            config[key] = value
    authorization = config.setdefault('authorization', {})
    config.setdefault('motion_limits', {'joint_velocity_rad_s': None,
                                      'joint_acceleration_rad_s2': None})
    if not isinstance(authorization, dict):
        raise ValueError('Deployment authorization must be an object')
    for key, name in (('trajectory_sha256', 'trajectory.json'),
                      ('manifest_sha256', 'source_manifest.json'),
                      ('export_report_sha256', 'export_report.json')):
        digest = sha256(trajectory.parent/name)
        if authorization.get(key) is None:
            authorization[key] = digest
        elif authorization[key] != digest:
            raise ValueError('Authorization bound to a different bundle: '+key)
    if allow_geometry_only:
        if curve.record['source'].get('check_mode') != 'geometry_only':
            raise ValueError('--allow-geometry-only requires a geometry_only source')
        config['execution_policy'] = {'mode': 'geometry_only', 'acknowledge_unverified_motion': True}
    else:
        config['execution_policy'] = {'mode': 'full'}
    payload = {'schema': PORTABLE_SCHEMA, 'deployment': config,
               'summary': {'points': len(curve.times), 'duration_s': curve.duration,
                           'source': curve.record['source']}, 'files': files}
    output = Path(output)
    output.mkdir(parents=True, exist_ok=False)
    reference = None
    if format == 'plain':
        payload = {'joint_names': curve.names,
                   'points': [{key: p[key] for key in POINT_FIELDS} for p in curve.record['points']]}
    write_json(output/'trajectory.json', payload)
    if format == 'plain':
        # The original bundle has already passed load_bundle; retain facts, not fake snapshots.
        reference = {'input_contract': PLAIN_CONTRACT,
                     'plain_trajectory_sha256': sha256(output/'trajectory.json'),
                     'points': len(curve.times),
                     'record': {k: v for k, v in curve.record.items() if k != 'points'},
                     'tcp_poses': [p['tcp_pose'] for p in curve.record['points']],
                     'export_report': report,
                     'source_fingerprints': {key: authorization[key] for key in SOURCE_HASH_FIELDS}}
        bindings = {'input_contract': PLAIN_CONTRACT,
                    'plain_trajectory_sha256': reference['plain_trajectory_sha256'],
                    'reference_sha256': canonical_sha256(reference)}
        # A prior approval of another contract must never silently authorize this one.
        for key, value in bindings.items():
            if not authorization.get('approved_by') and authorization.get(key) is None:
                authorization[key] = value
            else:
                authorization.setdefault(key, None)
        if read_json(output/'trajectory.json') != payload:
            raise ValueError('Plain trajectory round-trip differs from source points')
    script = build_standalone_script(config, reference)
    (output/'ur7e_saved_trajectory_executor.py').write_text(script, encoding='utf-8', newline='\n')
    return {'script': str((output/'ur7e_saved_trajectory_executor.py').resolve()),
            'trajectory': str((output/'trajectory.json').resolve()),
            'points': len(curve.times), 'duration_s': curve.duration,
            'execution_policy': config['execution_policy'],
            'format': format,
            'authorization_rebinding_required': format == 'plain' and any(
                authorization.get(key) != value for key, value in bindings.items()),
            'script_sha256': sha256(output/'ur7e_saved_trajectory_executor.py'),
            ('plain_trajectory_sha256' if format == 'plain' else 'portable_sha256'): sha256(output/'trajectory.json')}
